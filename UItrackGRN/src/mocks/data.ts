function makeLabels(): MaterialLabel[] {
  const out: MaterialLabel[] = [];
  let counter = 3451;
  for (const grn of grns) {
    for (const line of grn.lines) {
      const full = Math.floor(line.receivedQty / line.packingStandard);
      const rest = line.receivedQty % line.packingStandard;
      const total = full + (rest > 0 ? 1 : 0);
      for (let i = 0; i < Math.min(total, 12); i++) {
        counter += 1;
        const issued = i < Math.floor(line.issuedQty / line.packingStandard);
        out.push({
          labelUid: `LBL-${String(counter).padStart(8, "0")}`,
          grnNumber: grn.grnNumber,
          materialNumber: line.materialNumber,
          description: line.description,
          quantity: i === full ? rest : line.packingStandard,
          uom: line.materialNumber === "M021" ? "MTR" : "PCS",
          batch: line.batch,
          grnDate: grn.grnDate,
          binSequence: `${String(i + 1).padStart(2, "0")} of ${total}`,
          status: issued
            ? "Issued"
            : i < full - 1
              ? "Inwarded"
              : i % 5 === 0
                ? "Printed"
                : "Generated",
          printCount: issued ? 2 : 1,
          generatedAt: `${grn.grnDate}T09:${String(10 + i).padStart(2, "0")}:00`,
          issuedAt: issued ? `${grn.grnDate}T15:42:00` : undefined,
          issuedBy: issued ? "Rahul Sharma" : undefined,
        });
      }
    }
  }
  out[0]!.status = "Issued";
  out[0]!.issuedAt = "2026-08-14T15:42:00";
  out[0]!.issuedBy = "Rahul Sharma";
  return out;
}

